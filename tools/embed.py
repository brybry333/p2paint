#!/usr/bin/env python3
# embed.py <game dir> <out.h>: game/ (materials + the menu font) -> a header, so the mod writes its own game files
# (p2paint_runtime.cpp WriteGameFiles): one file to ship, on Linux and Windows. Run by make / win/build.sh.
import os, sys
root, out = sys.argv[1], sys.argv[2]
files = []
for d, _, names in os.walk(root):
    for n in names:
        p = os.path.join(d, n)
        files.append((os.path.relpath(p, root).replace(os.sep, '/'), open(p, 'rb').read()))
files.sort()
os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
with open(out + '.tmp', 'w') as f:
    f.write('// generated by tools/embed.py from game/ - do not edit\n#pragma once\n')
    for i, (rel, data) in enumerate(files):
        f.write('static const unsigned char s_File%d[%d] = {' % (i, len(data)))
        for k in range(0, len(data), 24):
            f.write('\n\t' + ','.join(str(b) for b in data[k:k + 24]) + ',')
        f.write('\n};\n')
    f.write('struct P2GameFile_t { const char *path; const unsigned char *data; unsigned int size; };\n')
    f.write('static const P2GameFile_t s_GameFiles[] = {\n')
    for i, (rel, data) in enumerate(files):
        f.write('\t{ "%s", s_File%d, %d },\n' % (rel, i, len(data)))
    f.write('};\n')
os.replace(out + '.tmp', out)
